// key → カテゴリ定義の索引（バリデーション等で O(1) 参照する）。
export const CAREER_VALUES_CATEGORY_BY_KEY: Record<
  CareerValuesCategoryKey,
  CareerValuesCategory
> = CAREER_VALUES_CATEGORIES.reduce(
  (acc, category) => {
    acc[category.key] = category;
    return acc;
  },
  {} as Record<CareerValuesCategoryKey, CareerValuesCategory>,
);

// 各カテゴリの「正規な選択肢集合」。保存時に未知の値を弾くために使う。
export const CAREER_VALUES_OPTION_SETS: Record<
  CareerValuesCategoryKey,
  ReadonlySet<string>
> = CAREER_VALUES_CATEGORY_KEYS.reduce(
  (acc, key) => {
    acc[key] = new Set(CAREER_VALUES_CATEGORY_BY_KEY[key].options);
    return acc;
  },
  {} as Record<CareerValuesCategoryKey, ReadonlySet<string>>,
);
