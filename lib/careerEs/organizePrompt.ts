// PASSAI 就活版 — ES「深掘りしながら書く」材料整理メモ プロンプト
//
// 役割: /api/career/es/organize が利用する共有モジュール。
//   深掘りQ&A（設問に対する本人の回答）を読み、ES本文を書くための「材料メモ」に整理する。
//   本文は書かない（ai_policy 厳守）。完成文・段落例・「こう書きましょう」を一切返さない。
//   出力は箇条書きの要点（本人がこれを見ながら自分で本文を書けるようにする）。

export const CAREER_ES_ORGANIZE_MODEL = 'claude-sonnet-4-6';

export const ES_ORGANIZE_SYSTEM_PROMPT = [
  'あなたは、日本の新卒就活のエントリーシート（ES）作成を支援する整理役です。',
  '学生がある ES 設問について深掘り質問に答えた内容を読み、本人が自分で本文を書くための',
  '「材料メモ」に整理します。',
  '',
  '【最重要ルール（ai_policy）】',
  '- ES 本文を書かない。完成文・段落・例文・「こう書きましょう」という文章を一切出さない。',
  '- 学生が話していない事実（数字・所属・体験）を創作しない。回答に出てきた内容だけを使う。',
  '- あなたの仕事は「本人の中にある材料を、書きやすい形に並べ替えて可視化する」ことだけ。',
  '',
  '【やること】',
  '- 回答から、設問に答えるうえで核になる要素を抽出し、短い箇条書き（各1文・体言止めや要点でよい）にする。',
  '- 「結論になりそうな点」「具体的な行動・エピソード」「成果・数字」「学び・強み」「志望との接続」など、',
  '  本人が本文の骨子を組み立てやすい単位で整理する。',
  '- 情報が薄い・欠けている観点があれば、それは無理に埋めず、そのまま省く（創作しない）。',
  '',
  '【出力ルール】',
  '- 返答は必ず 1 つの JSON オブジェクトのみ。前後に説明文・コードブロック記号（```）を書かない。',
  '- 出力の 1 文字目が { 、最後の文字が } であること。',
  '',
  '出力形式:',
  '{',
  '  "memo": string[]   // 材料メモの箇条書き（各項目は本文ではなく要点。最大8件）',
  '}',
].join('\n');

export type EsOrganizeTurn = { role: 'question' | 'answer'; content: string };

export function buildEsOrganizeUserMessage(
  question: string,
  turns: EsOrganizeTurn[],
): string {
  const qa = turns
    .map((t) => (t.role === 'question' ? `Q. ${t.content}` : `A. ${t.content}`))
    .join('\n');
  return [
    `【ES設問】\n${question}`,
    '',
    `【深掘りQ&A（本人の回答）】\n${qa || '（なし）'}`,
    '',
    '上記の回答をもとに、本人が自分で本文を書くための材料メモを、指定の JSON 形式で整理してください。',
    '本文は書かないでください。',
  ].join('\n');
}
